import {createHash, createPrivateKey, createPublicKey, sign} from 'node:crypto'
import {mkdir, readFile, writeFile} from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import {fileURLToPath} from 'node:url'

import {openapi, PROTOCOL_VERSION, schemaFileName, schemas} from './protocol-schema.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const checkOnly = process.argv.includes('--check')

function canonicalize(value) {
	if (value === null || typeof value === 'boolean' || typeof value === 'string') return JSON.stringify(value)
	if (typeof value === 'number') {
		if (!Number.isFinite(value)) throw new TypeError('Canonical JSON rejects non-finite numbers')
		return JSON.stringify(Object.is(value, -0) ? 0 : value)
	}

	if (Array.isArray(value)) return `[${value.map((entry) => canonicalize(entry)).join(',')}]`
	if (typeof value !== 'object') throw new TypeError(`Canonical JSON rejects ${typeof value}`)

	const prototype = Object.getPrototypeOf(value)
	if (prototype !== Object.prototype && prototype !== null) {
		throw new TypeError('Canonical JSON accepts only plain objects')
	}

	return `{${Object.keys(value)
		.sort()
		.map((key) => `${JSON.stringify(key)}:${canonicalize(value[key])}`)
		.join(',')}}`
}

const sha256Hex = (value) => createHash('sha256').update(value).digest('hex')
const digest = (value) => `sha256:${sha256Hex(value)}`
const base64url = (value) => Buffer.from(value).toString('base64url')

function refType(reference) {
	const file = path.basename(reference)
	const entry = Object.keys(schemas).find((name) => schemaFileName(name) === file)
	if (!entry) throw new Error(`Unknown schema reference: ${reference}`)
	return entry
}

function schemaToType(schema) {
	if (schema.$ref) return refType(schema.$ref)
	if ('const' in schema) return JSON.stringify(schema.const)
	if (schema.enum) return schema.enum.map((entry) => JSON.stringify(entry)).join(' | ')
	if (schema.oneOf) return schema.oneOf.map((entry) => schemaToType(entry)).join(' | ')
	if (schema.anyOf) return schema.anyOf.map((entry) => schemaToType(entry)).join(' | ')
	if (Array.isArray(schema.type)) {
		return schema.type.map((entry) => schemaToType({...schema, type: entry})).join(' | ')
	}

	switch (schema.type) {
		case 'null': {
			return 'null'
		}

		case 'boolean': {
			return 'boolean'
		}

		case 'integer':
		case 'number': {
			return 'number'
		}

		case 'string': {
			return 'string'
		}

		case 'array': {
			return `ReadonlyArray<${schemaToType(schema.items)}>`
		}

		case 'object': {
			const properties = schema.properties ?? {}
			const required = new Set(schema.required ?? [])
			const fields = Object.entries(properties).map(([name, property]) => {
				const safeName = /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name)
				return `\treadonly ${safeName}${required.has(name) ? '' : '?'}: ${schemaToType(property)}`
			})
			if (fields.length === 0 && schema.additionalProperties && schema.additionalProperties !== false) {
				return `{readonly [key: string]: ${schemaToType(schema.additionalProperties)}}`
			}

			return `{\n${fields.join('\n')}\n}`
		}

		default: {
			throw new Error(`Unsupported schema shape: ${JSON.stringify(schema)}`)
		}
	}
}

function generateTypes() {
	const lines = [
		'/* eslint-disable perfectionist/sort-object-types, perfectionist/sort-union-types */',
		'// Generated by scripts/generate-protocol.mjs. Do not edit.',
		`export const PROTOCOL_VERSION = ${JSON.stringify(PROTOCOL_VERSION)} as const`,
		'',
	]
	for (const [name, schema] of Object.entries(schemas)) {
		lines.push(`/** ${schema.description ?? schema.title} */`)
		lines.push(`export type ${name} = ${schemaToType(schema)}`)
		lines.push('')
	}

	return lines.join('\n')
}

function signingVectors() {
	const seed = Buffer.from('9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60', 'hex')
	const privateKey = createPrivateKey({
		key: Buffer.concat([Buffer.from('302e020100300506032b657004220420', 'hex'), seed]),
		format: 'der',
		type: 'pkcs8',
	})
	const publicKey = createPublicKey(privateKey)
		.export({format: 'der', type: 'spki'})
		.subarray(-32)

	const canonicalization = [
		{input: {b: 2, a: 1}, canonical: '{"a":1,"b":2}'},
		{input: {unicode: '€', controls: '\n', array: [3, true, null]}, canonical: undefined},
		{input: {negativeZero: -0, exponent: 1e30}, canonical: undefined},
	].map((vector) => {
		const canonical = vector.canonical ?? canonicalize(vector.input)
		return {...vector, canonical, digest: digest(Buffer.from(canonical, 'utf8'))}
	})

	const requestPayload = {
		protocolVersion: '1.0',
		deviceId: '018f6f5e-9c78-7a2f-8da8-b80e77f734f1',
		keyId: 'device-test-key-1',
		requestId: '018f6f5e-a263-7f79-8f72-64519e1b872f',
		timestamp: '2026-01-02T03:04:05.000Z',
		nonce: '7m4J_vlY6U0sWQTYhPj87w',
		method: 'POST',
		path: '/v1/sessions',
		bodyDigest: 'sha256:6b9a0b1b83f7a0c50ef3f1f28b4d994abe5bea17e6d26c5e1f43af595a0a437e',
		signatureAlgorithm: 'ed25519',
	}
	const eventPayload = {
		protocolVersion: '1.0',
		eventId: '018f6f5e-b21b-7168-93cb-e616baa51f09',
		sessionId: '018f6f5e-b0ce-7d67-b989-91d2e3e8ea7b',
		sequence: 1,
		occurredAt: '2026-01-02T03:04:06.000Z',
		eventType: 'heartbeat',
		correlationId: '018f6f5e-b273-7ed0-a364-9e715f1cf9af',
		causationId: null,
		payload: {},
		payloadDigest: digest(Buffer.from('{}')),
		previousEventHash: null,
		signer: {
			algorithm: 'ed25519',
			keyId: 'server-test-key-1',
			publicKey: base64url(publicKey),
		},
	}

	const signedVector = (payload) => {
		const canonical = canonicalize(payload)
		return {
			payload,
			canonical,
			digest: digest(Buffer.from(canonical, 'utf8')),
			signature: base64url(sign(null, Buffer.from(canonical, 'utf8'), privateKey)),
		}
	}

	return {
		protocolVersion: PROTOCOL_VERSION,
		algorithm: 'RFC8785-compatible JCS using UTF-8, then Ed25519',
		key: {
			keyId: 'rfc8032-test-key-1',
			seedHex: seed.toString('hex'),
			publicKey: base64url(publicKey),
		},
		canonicalization,
		request: signedVector(requestPayload),
		event: signedVector(eventPayload),
	}
}

const output = new Map()
for (const [name, schema] of Object.entries(schemas)) {
	output.set(`protocol/schemas/${schemaFileName(name)}`, `${JSON.stringify(schema, null, 2)}\n`)
}
output.set('protocol/openapi.json', `${JSON.stringify(openapi, null, 2)}\n`)
output.set('protocol/signing-vectors.json', `${JSON.stringify(signingVectors(), null, 2)}\n`)
output.set('src/protocol/generated.ts', generateTypes())

const fileDigests = Object.fromEntries(
	[...output.entries()].map(([file, contents]) => [file, digest(Buffer.from(contents, 'utf8'))]),
)
const contractInput = Object.entries(fileDigests)
	.sort(([left], [right]) => left.localeCompare(right))
	.map(([file, fileDigest]) => `${file}:${fileDigest}\n`)
	.join('')
output.set(
	'protocol/manifest.json',
	`${JSON.stringify(
		{
			protocolVersion: PROTOCOL_VERSION,
			canonicalization: 'path-sorted UTF-8 file digest manifest',
			contractDigest: digest(Buffer.from(contractInput, 'utf8')),
			files: fileDigests,
		},
		null,
		2,
	)}\n`,
)

const drift = []
for (const [relativePath, contents] of output) {
	const absolutePath = path.join(root, relativePath)
	if (checkOnly) {
		let current
		try {
			current = await readFile(absolutePath, 'utf8')
		} catch {
			current = undefined
		}

		if (current !== contents) drift.push(relativePath)
	} else {
		await mkdir(path.dirname(absolutePath), {recursive: true})
		await writeFile(absolutePath, contents)
	}
}

if (drift.length > 0) {
	console.error(`Protocol generation drift:\n${drift.map((file) => `- ${file}`).join('\n')}`)
	process.exitCode = 1
} else if (checkOnly) {
	console.log(`Protocol ${PROTOCOL_VERSION} generated artifacts are current.`)
} else {
	console.log(`Generated protocol ${PROTOCOL_VERSION}: ${output.get('protocol/manifest.json').match(/sha256:[a-f0-9]{64}/)[0]}`)
}
